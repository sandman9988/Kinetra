def load_m1_csv(path: Path) -> Optional[pd.DataFrame]:
    """Load an M1 CSV file with automatic format detection.

    Handles both comma-separated and tab-separated files, with or without
    header rows.  Normalises column names to canonical lowercase form.

    Parameters
    ----------
    path : Path
        Path to the M1 CSV file.

    Returns
    -------
    pd.DataFrame or None
        Loaded and normalised DataFrame, or None on failure.
    """
    if not path.exists():
        logger.warning("M1 file not found: %s", path)
        return None

    # Fast path: use PyArrow-accelerated reader for comma-separated CSVs
    # (canonical Kinetra format).  ~20× faster than pd.read_csv on large
    # M1 files (950K rows: ~50 ms vs ~1177 ms).  The time column is parsed
    # natively in C++ — downstream aggregate_ohlcv() handles the already-
    # parsed datetime column gracefully (to_datetime on datetime64 is a no-op).
    from kinetra.csv_reader import read_ohlcv_fast

    try:
        df = read_ohlcv_fast(path, sort=False, deduplicate=False)
        df = normalise_m1_columns(df)
        return df
    except Exception:
        pass

    # Fallback: tab-separated (MT5 export format) — pyarrow doesn't handle
    # tab-separated well, so use pandas C-engine directly.
    try:
        df = pd.read_csv(path, sep="\t")
        df = normalise_m1_columns(df)
        return df
    except Exception as exc:
        logger.error("Failed to read %s: %s", path, exc)
        return None


def _extract_symbol_from_path(path: Path) -> str:
    """Extract the instrument symbol from a file path.

    Expected patterns:
      - ``…/SYMBOL/SYMBOL_M1_*.csv`` → ``SYMBOL``
      - ``…/SYMBOL_M1_*.csv`` → ``SYMBOL``

    Falls back to the parent directory name if the filename pattern
    doesn't match.
    """
    stem = path.stem  # e.g. "EURUSD_M1_202201010000_202312310000"
    parts = stem.split("_")
    if len(parts) >= 2:
        return parts[0]
    # Fallback: use parent directory name
    return path.parent.name


def _extract_dates_from_path(path: Path) -> Tuple[str, str]:
    """Extract start and end date strings from an M1 filename.

    Expected pattern: ``SYMBOL_M1_YYYYMMDDHHNN_YYYYMMDDHHNN.csv``

    Returns
    -------
    (start_str, end_str) : Tuple[str, str]
        Date strings, or empty strings if parsing fails.
    """
    stem = path.stem
    parts = stem.split("_")
    if len(parts) >= 4:
        return parts[2], parts[3]
    return "", ""


def aggregate_m1_file(
    m1_path: Path,
    target_tf: str,
    output_dir: Optional[Path] = None,
    *,
    symbol: Optional[str] = None,
    overwrite: bool = False,
) -> AggregationResult:
    """Aggregate a single M1 CSV file to a target timeframe and save.

    Parameters
    ----------
    m1_path : Path
        Path to the M1 CSV file.
    target_tf : str
        Target timeframe (e.g. ``"H1"``).
    output_dir : Path or None
        Directory to write the output file.  If None, uses the default
        ``data/aggregated/{TF}/{category}/{SYMBOL}/`` layout.
    symbol : str or None
        Override symbol name (auto-detected from path if None).
    overwrite : bool
        If True, overwrite existing output files.  If False, skip
        files that already exist.

    Returns
    -------
    AggregationResult
        Result of the aggregation including output path and statistics.
    """
    t0 = time.monotonic()
    sym = symbol or _extract_symbol_from_path(m1_path)

    # Load
    df = load_m1_csv(m1_path)
    if df is None:
        return AggregationResult(
            symbol=sym,
            target_tf=target_tf,
            success=False,
            error=f"Failed to load M1 file: {m1_path}",
            elapsed_seconds=time.monotonic() - t0,
        )

    source_bars = len(df)

    # Determine output path
    if output_dir is None:
        # Auto-detect category from the M1 path structure
        # Expected: data/master_m1/{category}/{SYMBOL}/SYMBOL_M1_*.csv
        # or legacy: data/master_standardized/{category}/{SYMBOL}/SYMBOL_M1_*.csv
        category = _infer_category_from_path(m1_path)
        project_root = _find_project_root(m1_path)
        output_dir = project_root / AGGREGATED_DATA_DIR / target_tf / category / sym

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Build output filename
    start_str, end_str = _extract_dates_from_path(m1_path)
    if start_str and end_str:
        out_filename = f"{sym}_{target_tf}_{start_str}_{end_str}.csv"
    else:
        # Derive dates from the data itself
        if "time" in df.columns:
            times = pd.to_datetime(df["time"], errors="coerce").dropna()
            if len(times) >= 2:
                start_str = times.iloc[0].strftime("%Y%m%d%H%M")
                end_str = times.iloc[-1].strftime("%Y%m%d%H%M")
                out_filename = f"{sym}_{target_tf}_{start_str}_{end_str}.csv"
            else:
                out_filename = f"{sym}_{target_tf}.csv"
        else:
            out_filename = f"{sym}_{target_tf}.csv"

    out_path = output_dir / out_filename

    # Check if already exists
    if out_path.exists() and not overwrite:
        return AggregationResult(
            symbol=sym,
            target_tf=target_tf,
            source_bars=source_bars,
            target_bars=0,
            output_path=out_path,
            success=True,
            error="skipped (already exists)",
            elapsed_seconds=time.monotonic() - t0,
        )

    # Aggregate
    result_df = aggregate_ohlcv(df, target_tf, symbol=sym)
    if result_df is None:
        return AggregationResult(
            symbol=sym,
            target_tf=target_tf,
            source_bars=source_bars,
            success=False,
            error=f"Aggregation produced no output for {sym} → {target_tf}",
            elapsed_seconds=time.monotonic() - t0,
        )

    target_bars = len(result_df)
    compression = source_bars / max(target_bars, 1)

    # Save atomically (write to temp, then rename)
    try:
        _atomic_write_csv(result_df, out_path)
    except Exception as exc:
        return AggregationResult(
            symbol=sym,
            target_tf=target_tf,
            source_bars=source_bars,
            target_bars=target_bars,
            compression_ratio=compression,
            success=False,
            error=f"Failed to write {out_path}: {exc}",
            elapsed_seconds=time.monotonic() - t0,
        )

    return AggregationResult(
        symbol=sym,
        target_tf=target_tf,
        source_bars=source_bars,
        target_bars=target_bars,
        compression_ratio=compression,
        output_path=out_path,
        success=True,
        elapsed_seconds=time.monotonic() - t0,
    )


def aggregate_m1_to_all(
    m1_path: Path,
    timeframes: Optional[Sequence[str]] = None,
    output_base: Optional[Path] = None,
    *,
    symbol: Optional[str] = None,
    overwrite: bool = False,
) -> List[AggregationResult]:
    """Aggregate a single M1 file to all requested timeframes.

    Parameters
    ----------
    m1_path : Path
        Path to the M1 CSV file.
    timeframes : sequence of str or None
        Target timeframes.  Defaults to ``DEFAULT_TIMEFRAMES``.
    output_base : Path or None
        Base directory for aggregated output.  If None, uses the default
        layout under ``data/aggregated/``.
    symbol : str or None
        Override symbol name.
    overwrite : bool
        If True, overwrite existing files.

    Returns
    -------
    List[AggregationResult]
        One result per target timeframe.
    """
    if timeframes is None:
        timeframes = DEFAULT_TIMEFRAMES

    sym = symbol or _extract_symbol_from_path(m1_path)
    results = []

    for tf in timeframes:
        if tf not in TIMEFRAME_MINUTES:
            results.append(
                AggregationResult(
                    symbol=sym,
                    target_tf=tf,
                    success=False,
                    error=f"Unsupported timeframe: {tf}",
                )
            )
            continue

        if output_base is not None:
            category = _infer_category_from_path(m1_path)
            broker_path = _infer_broker_path_from_path(m1_path)
            if broker_path:
                out_dir = output_base / tf / Path(broker_path) / category / sym
            else:
                out_dir = output_base / tf / category / sym
        else:
            out_dir = None

        result = aggregate_m1_file(
            m1_path,
            tf,
            output_dir=out_dir,
            symbol=sym,
            overwrite=overwrite,
        )
        results.append(result)

    return results


def aggregate_batch(
    m1_dir: Path,
    timeframes: Optional[Sequence[str]] = None,
    output_base: Optional[Path] = None,
    *,
    symbols: Optional[List[str]] = None,
    overwrite: bool = False,
    max_workers: Optional[int] = None,
) -> BatchAggregationReport:
    """Aggregate all M1 files in a directory tree to higher timeframes.

    Parameters
    ----------
    m1_dir : Path
        Root directory containing M1 CSV files (searched recursively).
    timeframes : sequence of str or None
        Target timeframes.  Defaults to ``DEFAULT_TIMEFRAMES``.
    output_base : Path or None
        Base directory for output.
    symbols : list of str or None
        If provided, only process these symbols.  Others are skipped.
    overwrite : bool
        Overwrite existing aggregated files.

    Returns
    -------
    BatchAggregationReport
        Summary of the batch run.
    """
    t0 = time.monotonic()
    report = BatchAggregationReport()

    m1_files = discover_m1_files(m1_dir)
    if not m1_files:
        report.errors.append(f"No M1 files found in {m1_dir}")
        report.total_elapsed_seconds = time.monotonic() - t0
        return report

    logger.info("Found %d M1 files in %s", len(m1_files), m1_dir)

    selected_files: List[Path] = []
    if symbols is None:
        selected_files = m1_files
    else:
        wanted = {s.strip().upper() for s in symbols if s and s.strip()}
        for m1_path in m1_files:
            sym = _extract_symbol_from_path(m1_path).upper()
            iid = _instrument_id_from_path(m1_path).upper()
            if sym in wanted or iid in wanted:
                selected_files.append(m1_path)

    if not selected_files:
        report.errors.append("No matching M1 files after symbol/instrument filter")
        report.total_elapsed_seconds = time.monotonic() - t0
        return report

    workers = max_workers if max_workers is not None else int(os.getenv("KINETRA_AGG_WORKERS", "4"))
    workers = max(1, int(workers))

    def _run_one(path: Path) -> List[AggregationResult]:
        sym = _extract_symbol_from_path(path)
        return aggregate_m1_to_all(
            path,
            timeframes=timeframes,
            output_base=output_base,
            symbol=sym,
            overwrite=overwrite,
        )

    if workers == 1 or len(selected_files) == 1:
        all_results = [_run_one(p) for p in selected_files]
    else:
        with ThreadPoolExecutor(max_workers=workers) as pool:
            all_results = list(pool.map(_run_one, selected_files))

    for results in all_results:
        for r in results:
            report.results.append(r)
            if r.success and r.error != "skipped (already exists)":
                report.total_m1_bars += r.source_bars
                report.total_output_bars += r.target_bars
                report.total_files_written += 1
            elif not r.success:
                report.errors.append(f"{r.symbol} → {r.target_tf}: {r.error}")

    report.total_elapsed_seconds = time.monotonic() - t0
    return report


