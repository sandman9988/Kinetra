@dataclass(frozen=True, slots=True)
class AggregationResult:
    """Result of aggregating one M1 file to a target timeframe.

    Attributes
    ----------
    symbol : str
        Instrument symbol (e.g. ``"EURUSD"``).
    source_tf : str
        Source timeframe (always ``"M1"``).
    target_tf : str
        Target timeframe (e.g. ``"H1"``).
    source_bars : int
        Number of M1 bars in the source.
    target_bars : int
        Number of bars in the aggregated output.
    compression_ratio : float
        ``source_bars / target_bars`` — how many M1 bars per target bar.
    output_path : Optional[Path]
        Where the aggregated file was written (None if not saved).
    elapsed_seconds : float
        Wall-clock time for the aggregation.
    success : bool
        Whether the aggregation completed without errors.
    error : Optional[str]
        Error message if ``success`` is False.
    """

    symbol: str
    source_tf: str = "M1"
    target_tf: str = ""
    source_bars: int = 0
    target_bars: int = 0
    compression_ratio: float = 0.0
    output_path: Optional[Path] = None
    elapsed_seconds: float = 0.0
    success: bool = True
    error: Optional[str] = None


@dataclass
class BatchAggregationReport:
    """Summary of a batch aggregation run across multiple symbols/timeframes.

    Attributes
    ----------
    results : List[AggregationResult]
        Individual results for each symbol/timeframe pair.
    total_m1_bars : int
        Total M1 bars processed across all symbols.
    total_output_bars : int
        Total aggregated bars produced.
    total_files_written : int
        Number of output files successfully written.
    total_elapsed_seconds : float
        Wall-clock time for the entire batch.
    errors : List[str]
        Error messages from failed aggregations.
    """

    results: List[AggregationResult] = field(default_factory=list)
    total_m1_bars: int = 0
    total_output_bars: int = 0
    total_files_written: int = 0
    total_elapsed_seconds: float = 0.0
    errors: List[str] = field(default_factory=list)

    @property
    def success_count(self) -> int:
        return sum(1 for r in self.results if r.success)

    @property
    def failure_count(self) -> int:
        return sum(1 for r in self.results if not r.success)

    def summary(self) -> str:
        """Human-readable summary of the batch run."""
        lines = [
            f"Aggregation complete: {self.success_count} succeeded, {self.failure_count} failed",
            f"  M1 bars processed:    {self.total_m1_bars:,}",
            f"  Output bars produced: {self.total_output_bars:,}",
            f"  Files written:        {self.total_files_written}",
            f"  Elapsed:              {self.total_elapsed_seconds:.1f}s",
        ]
        if self.errors:
            lines.append(f"  Errors ({len(self.errors)}):")
            for err in self.errors[:10]:
                lines.append(f"    • {err}")
            if len(self.errors) > 10:
                lines.append(f"    … and {len(self.errors) - 10} more")
        return "\n".join(lines)


