#: Supported target timeframes with their duration in minutes.
#: Ordered from finest to coarsest.  M1 is NOT listed because it is the source.
TIMEFRAME_MINUTES: Dict[str, int] = {
    "M5": 5,
    "M15": 15,
    "M30": 30,
    "H1": 60,
    "H4": 240,
    "D1": 1440,
    "W1": 10080,
}

#: All supported target timeframe labels (for iteration / validation).
SUPPORTED_TIMEFRAMES: Tuple[str, ...] = tuple(TIMEFRAME_MINUTES.keys())

#: Default set of timeframes to generate when no explicit list is given.
#: Renko-only architecture: M30 is the sole required aggregation target.
#: DSP (Variance Ratio) and brick construction both operate on M30 closes.
#: Other timeframes (M5, M15, H1, H4) remain SUPPORTED but are no longer
#: generated by default — pass them explicitly if needed for research.
DEFAULT_TIMEFRAMES: Tuple[str, ...] = ("M30",)

#: Pandas offset aliases used for resampling.
_TF_RESAMPLE_RULE: Dict[str, str] = {
    "M5": "5min",
    "M15": "15min",
    "M30": "30min",
    "H1": "1h",
    "H4": "4h",
    "D1": "1D",
    "W1": "1W",
}

#: Minimum M1 bars required to produce a meaningful aggregated file.
#: At M1 resolution, 1440 bars ≈ 1 trading day.
MIN_M1_BARS: int = 1000

#: Canonical OHLCV columns expected in M1 source data (lowercase).
CANONICAL_COLUMNS: Tuple[str, ...] = ("time", "open", "high", "low", "close", "volume")

#: Optional columns that are carried through aggregation when present.
OPTIONAL_COLUMNS: Tuple[str, ...] = ("spread",)

#: M1 data directory (relative to project root).
#: Points to the canonical multi-broker storage root.
#: NOTE: The old "data/master_m1" path was a phantom — all active downloaders
#: (MetaAPI, cTrader, MT5) write to data/master_standardized/.  This constant
#: is kept for any code that references it by name but must resolve correctly.
M1_DATA_DIR: str = "data/master_standardized"

#: Aggregated data directory (relative to project root).
AGGREGATED_DATA_DIR: str = "data/aggregated"


