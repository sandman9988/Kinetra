"""
Timeframe Aggregation Module
=============================

Canonical chokepoint for deriving higher timeframes from M1 OHLCV data.

Design decisions (from RENKO_KINETRA_DESIGN_SPEC.md §4.3):
  - M1 is the ONLY source timeframe downloaded from brokers.
  - All higher timeframes (M5, M15, M30, H1, H4, D1, W1) are aggregated from M1.
  - Aggregated files are cache, not source — always re-derivable from M1.
  - If M1 is updated (new bars downloaded), aggregated files MUST be regenerated.

Aggregation rules (standard OHLCV):
  open   = first open in window
  high   = max high in window
  low    = min low in window
  close  = last close in window
  volume = sum of tick_volume in window
  spread = median spread in window (representative, not sum)

This module is the canonical home for all timeframe aggregation logic.
Import from here — never duplicate.

Usage::

    from kinetra.aggregation import (
        aggregate_ohlcv,
        aggregate_m1_to_timeframe,
        aggregate_m1_to_all,
        discover_m1_files,
        AggregationResult,
        SUPPORTED_TIMEFRAMES,
    )

See Also:
    - ``docs/MANUAL.md §4.3`` — design specification
    - ``kinetra/broker.py`` — OHLCV normalisation (upstream)
    - ``kinetra/renko/brick_engine.py`` — Renko construction (downstream)
"""

