def _find_project_root(path: Path) -> Path:
    """Walk up from ``path`` looking for a directory containing ``kinetra/``.

    Falls back to ``path.parent.parent.parent`` if the marker is not found.
    """
    current = path.resolve()
    for _ in range(10):
        if (current / "kinetra").is_dir():
            return current
        parent = current.parent
        if parent == current:
            break
        current = parent

    # Fallback: assume data/master_m1/{cat}/{sym}/file.csv → 4 levels up
    return path.resolve().parent.parent.parent.parent


_KNOWN_CATEGORIES = frozenset(
    ("forex", "crypto", "metals", "energy", "indices", "commodities", "other")
)


def _infer_category_from_path(path: Path) -> str:
    """Infer the asset category from the file path.

    Expected layouts (from shallowest to deepest)::

      ``data/master_m1/{category}/{SYMBOL}/file.csv``
      ``data/master_standardized/{category}/{SYMBOL}/file.csv``
      ``data/master_standardized/{broker}/{category}/{SYMBOL}/file.csv``
      ``data/master_standardized/{broker_type}/{account}/{category}/{SYMBOL}/file.csv``

    The function scans up to 3 levels past the data-directory marker to
    find the first path component that matches a known category name.

    Returns ``"other"`` if the category cannot be inferred.
    """
    parts = path.resolve().parts
    # Look for known data directory markers
    for i, part in enumerate(parts):
        if part in ("master_m1", "master_standardized", "aggregated"):
            # Scan up to 3 components past the marker to find a category.
            # This handles:
            #   marker/{category}/…                (depth 1 — legacy flat)
            #   marker/{broker}/{category}/…        (depth 2 — single-level broker)
            #   marker/{broker_type}/{account}/{category}/…  (depth 3 — §28 multi-broker)
            for offset in range(1, 4):
                idx = i + offset
                if idx < len(parts):
                    candidate = parts[idx].lower()
                    if candidate in _KNOWN_CATEGORIES:
                        return candidate

    return "other"


def _infer_broker_path_from_path(path: Path) -> str:
    """Infer broker/account subpath from an M1 source file path.

    Returns an empty string for legacy flat layouts with no broker namespace.
    """
    parts = path.resolve().parts
    marker_idx = -1
    for i, part in enumerate(parts):
        if part in ("master_standardized", "master_m1"):
            marker_idx = i
            break
    if marker_idx < 0:
        return ""

    category_idx = -1
    for offset in range(1, 6):
        idx = marker_idx + offset
        if idx < len(parts) and parts[idx].lower() in _KNOWN_CATEGORIES:
            category_idx = idx
            break
    if category_idx < 0:
        return ""

    broker_parts = parts[marker_idx + 1 : category_idx]
    return "/".join(p for p in broker_parts if p)


def _instrument_id_from_path(path: Path) -> str:
    """Build broker-qualified instrument id for uniqueness across brokers."""
    symbol = _extract_symbol_from_path(path)
    broker_path = _infer_broker_path_from_path(path)
    return f"{broker_path}/{symbol}" if broker_path else symbol


def _atomic_write_csv(df: pd.DataFrame, path: Path) -> None:
    """Write a DataFrame to CSV atomically (write-to-temp then rename).

    Parameters
    ----------
    df : pd.DataFrame
        Data to write.
    path : Path
        Destination path.
    """
    import shutil
    import tempfile

    path.parent.mkdir(parents=True, exist_ok=True)

    # Write to a temporary file in the same directory (same filesystem for atomic rename)
    fd, tmp_path = tempfile.mkstemp(
        dir=path.parent,
        prefix=f".{path.stem}_",
        suffix=".csv.tmp",
    )
    try:
        df.to_csv(tmp_path, index=False)
        # Atomic rename (same filesystem)
        shutil.move(tmp_path, str(path))
    except Exception:
        # Clean up temp file on failure
        try:
            Path(tmp_path).unlink(missing_ok=True)
        except Exception:
            pass
        raise
    finally:
        try:
            os.close(fd)
        except Exception:
            pass


