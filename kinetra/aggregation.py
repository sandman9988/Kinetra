def validate_m1_dataframe(df: pd.DataFrame, symbol: str = "UNKNOWN") -> Tuple[bool, str]:
    """Validate that a DataFrame contains valid M1 OHLCV data.

    Parameters
    ----------
    df : pd.DataFrame
        DataFrame to validate.  Must have ``time``, ``open``, ``high``,
        ``low``, ``close``, ``volume`` columns.
    symbol : str
        Symbol name for error messages.

    Returns
    -------
    (valid, message) : Tuple[bool, str]
        ``valid`` is True if the data passes all checks.
        ``message`` describes the first failure found, or "OK".
    """
    if df is None or df.empty:
        return False, f"{symbol}: DataFrame is empty or None"

    # Check required columns — 'time' can be the index (DatetimeIndex) instead
    # of a regular column, which is perfectly valid for aggregation.
    required_price_cols = [c for c in CANONICAL_COLUMNS if c != "time"]
    has_time = (
        "time" in df.columns
        or isinstance(df.index, pd.DatetimeIndex)
        or (hasattr(df.index, "name") and df.index.name == "time")
    )
    missing = [c for c in required_price_cols if c not in df.columns]
    if missing:
        # Try case-insensitive match
        df_cols_lower = {c.lower(): c for c in df.columns}
        still_missing = [c for c in missing if c.lower() not in df_cols_lower]
        if still_missing:
            return False, f"{symbol}: missing columns: {still_missing}"
    if not has_time:
        # Try case-insensitive match for time
        df_cols_lower = {c.lower(): c for c in df.columns}
        if "time" not in df_cols_lower:
            return False, f"{symbol}: missing columns: ['time']"

    if len(df) < MIN_M1_BARS:
        return False, f"{symbol}: only {len(df)} bars (need ≥{MIN_M1_BARS})"

    # Check for NaN in price columns
    price_cols = ["open", "high", "low", "close"]
    available_price_cols = [c for c in price_cols if c in df.columns]
    nan_count = df[available_price_cols].isna().sum().sum()
    if nan_count > 0:
        return False, f"{symbol}: {nan_count} NaN values in price columns"

    # Check for non-positive prices
    for col in available_price_cols:
        if (df[col] <= 0).any():
            return False, f"{symbol}: non-positive values in '{col}'"

    # Check OHLC consistency: high ≥ low
    if "high" in df.columns and "low" in df.columns:
        violations = (df["high"] < df["low"]).sum()
        if violations > 0:
            return False, f"{symbol}: {violations} bars where high < low"

    return True, "OK"


def normalise_m1_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Normalise column names to lowercase canonical form.

    Handles common variations: ``Open``→``open``, ``Time``→``time``,
    ``tickVolume``→``volume``, ``tick_volume``→``volume``.

    Parameters
    ----------
    df : pd.DataFrame
        Raw M1 DataFrame.

    Returns
    -------
    pd.DataFrame
        DataFrame with canonical lowercase column names.
    """
    rename_map = {}
    col_lower = {c.lower(): c for c in df.columns}

    # Standard case normalisation
    for canon in CANONICAL_COLUMNS + OPTIONAL_COLUMNS:
        if canon not in df.columns and canon in col_lower:
            rename_map[col_lower[canon]] = canon
        elif canon not in df.columns:
            # Check common aliases
            aliases = {
                "volume": ["tickvolume", "tick_volume", "vol", "tickvol"],
                "time": ["datetime", "date", "timestamp"],
            }
            for alias in aliases.get(canon, []):
                if alias in col_lower:
                    rename_map[col_lower[alias]] = canon
                    break

    if rename_map:
        df = df.rename(columns=rename_map)

    return df


def aggregate_ohlcv(
    df_m1: pd.DataFrame,
    target_tf: str,
    *,
    validate: bool = True,
    symbol: str = "UNKNOWN",
) -> Optional[pd.DataFrame]:
    """Aggregate M1 OHLCV data to a higher timeframe.

    This is the canonical aggregation function.  All other aggregation
    entry points delegate to this.

    Parameters
    ----------
    df_m1 : pd.DataFrame
        M1 OHLCV data with columns: ``time``, ``open``, ``high``, ``low``,
        ``close``, ``volume``.  Optionally ``spread``.
    target_tf : str
        Target timeframe label: one of ``SUPPORTED_TIMEFRAMES``
        (``"M5"``, ``"M15"``, ``"M30"``, ``"H1"``, ``"H4"``, ``"D1"``, ``"W1"``).
    validate : bool
        If True, validate the input DataFrame before aggregating.
    symbol : str
        Symbol name for logging / error messages.

    Returns
    -------
    pd.DataFrame or None
        Aggregated OHLCV DataFrame with the same column schema as input,
        or None if validation fails or no bars can be produced.

    Raises
    ------
    ValueError
        If ``target_tf`` is not in ``SUPPORTED_TIMEFRAMES``.

    Notes
    -----
    Aggregation rules:

    - ``open``   = first open in each window
    - ``high``   = max high in each window
    - ``low``    = min low in each window
    - ``close``  = last close in each window
    - ``volume`` = sum of volume in each window
    - ``spread`` = median spread in each window (if present)

    The function uses ``pandas.DataFrame.resample()`` with ``label='left'``
    and ``closed='left'`` semantics, matching the MetaAPI / MT5 convention
    where the bar timestamp marks the **start** of the bar's time window.

    Examples
    --------
    >>> import pandas as pd
    >>> from kinetra.aggregation import aggregate_ohlcv
    >>> m1 = pd.read_csv("data/master_standardized/forex/EURUSD/EURUSD_M1_*.csv")
    >>> h1 = aggregate_ohlcv(m1, "H1", symbol="EURUSD")
    >>> print(h1.shape)  # 60× fewer rows than M1
    """
    if target_tf not in TIMEFRAME_MINUTES:
        raise ValueError(
            f"Unsupported target timeframe '{target_tf}'. "
            f"Must be one of: {', '.join(SUPPORTED_TIMEFRAMES)}"
        )

    # Normalise columns
    df = normalise_m1_columns(df_m1.copy())

    # Validate
    if validate:
        valid, msg = validate_m1_dataframe(df, symbol)
        if not valid:
            logger.warning("Validation failed for %s: %s", symbol, msg)
            return None

    # Ensure 'time' is datetime and set as index for resampling
    if "time" in df.columns:
        df["time"] = pd.to_datetime(df["time"], utc=True, errors="coerce")
        df = df.dropna(subset=["time"])
        df = df.set_index("time")
    elif isinstance(df.index, pd.DatetimeIndex):
        if df.index.tz is None:
            df.index = df.index.tz_localize("UTC")
    else:
        logger.warning("%s: no 'time' column and index is not DatetimeIndex", symbol)
        return None

    # Sort ascending (paranoia — MetaAPI sometimes returns descending)
    df = df.sort_index()

    # Remove duplicates
    df = df[~df.index.duplicated(keep="first")]

    # Build aggregation dict
    agg_dict = {
        "open": "first",
        "high": "max",
        "low": "min",
        "close": "last",
        "volume": "sum",
    }

    # Handle optional columns
    has_spread = "spread" in df.columns
    if has_spread:
        agg_dict["spread"] = "median"

    # Only aggregate columns that exist
    agg_dict = {k: v for k, v in agg_dict.items() if k in df.columns}

    if not agg_dict:
        logger.warning("%s: no OHLCV columns found after normalisation", symbol)
        return None

    # Resample
    rule = _TF_RESAMPLE_RULE[target_tf]
    try:
        resampled = df.resample(rule, label="left", closed="left").agg(agg_dict)
    except Exception as exc:
        logger.error("%s → %s: resample failed: %s", symbol, target_tf, exc)
        return None

    # Drop bars where all OHLC are NaN (weekend/holiday gaps produce these)
    price_cols = [c for c in ("open", "high", "low", "close") if c in resampled.columns]
    resampled = resampled.dropna(subset=price_cols, how="all")

    if resampled.empty:
        logger.warning("%s → %s: no bars after aggregation", symbol, target_tf)
        return None

    # Forward-fill any remaining NaN in price columns (partial windows at boundaries)
    for col in price_cols:
        resampled[col] = resampled[col].ffill()

    # Fill volume NaN with 0
    if "volume" in resampled.columns:
        resampled["volume"] = resampled["volume"].fillna(0).astype(np.int64)

    # Fill spread NaN with forward-fill then 0
    if has_spread and "spread" in resampled.columns:
        resampled["spread"] = resampled["spread"].ffill().fillna(0)

    # Reset index to get 'time' back as a column
    resampled = resampled.reset_index()
    resampled = resampled.rename(columns={"index": "time"})

    # Ensure time column name is correct
    if "time" not in resampled.columns and resampled.columns[0] != "time":
        # The reset_index might use the index name
        first_col = resampled.columns[0]
        if pd.api.types.is_datetime64_any_dtype(resampled[first_col]):
            resampled = resampled.rename(columns={first_col: "time"})

    # Validate OHLC consistency in output
    if "high" in resampled.columns and "low" in resampled.columns:
        # Fix any floating-point edge cases
        mask = resampled["high"] < resampled["low"]
        if mask.any():
            resampled.loc[mask, "high"] = resampled.loc[mask, ["high", "low"]].max(axis=1)

    compression = len(df) / max(len(resampled), 1)
    logger.info(
        "%s: M1 (%d bars) → %s (%d bars), compression %.1f:1",
        symbol,
        len(df),
        target_tf,
        len(resampled),
        compression,
    )

    return resampled


