def discover_m1_files(
    root_dir: Path,
    *,
    min_size_bytes: int = 1024,
) -> List[Path]:
    """Recursively discover M1 CSV files in a directory tree.

    Matches files named ``*_M1_*.csv`` (case-insensitive) that are at least
    ``min_size_bytes`` in size.

    Parameters
    ----------
    root_dir : Path
        Root directory to search.
    min_size_bytes : int
        Minimum file size to consider.  Tiny files are likely empty or corrupt.

    Returns
    -------
    List[Path]
        Sorted list of M1 file paths.
    """
    root = Path(root_dir)
    if not root.exists():
        return []

    m1_files = []
    for csv_path in root.rglob("*.csv"):
        stem_upper = csv_path.stem.upper()
        if "_M1_" in stem_upper or stem_upper.endswith("_M1"):
            if csv_path.stat().st_size >= min_size_bytes:
                m1_files.append(csv_path)

    return sorted(m1_files)


def discover_m1_symbols(root_dir: Path) -> Dict[str, Path]:
    """Discover M1 files and return a symbol → path mapping.

    When multiple M1 files exist for the same symbol, the largest file
    (most complete data) is selected.

    Parameters
    ----------
    root_dir : Path
        Root directory to search.

    Returns
    -------
    Dict[str, Path]
        Mapping of symbol name to its best M1 file path.
    """
    files = discover_m1_files(root_dir)
    symbols: Dict[str, Path] = {}

    for path in files:
        sym = _extract_symbol_from_path(path)
        if sym not in symbols or path.stat().st_size > symbols[sym].stat().st_size:
            symbols[sym] = path

    return symbols


def discover_m1_instruments(root_dir: Path) -> Dict[str, Path]:
    """Discover M1 files keyed by broker-qualified instrument id.

    Example ids:
      - ``metaapi/vantage_demo_12345/XAUUSD``
      - ``ctrader/pepperstone_live_9988/NAS100``
      - ``EURUSD`` (legacy flat layout)
    """
    files = discover_m1_files(root_dir)
    instruments: Dict[str, Path] = {}
    for path in files:
        iid = _instrument_id_from_path(path)
        if iid not in instruments or path.stat().st_size > instruments[iid].stat().st_size:
            instruments[iid] = path
    return instruments


def check_aggregation_freshness(
    m1_path: Path,
    aggregated_dir: Path,
    target_tf: str,
) -> bool:
    """Check if aggregated data is up-to-date relative to the M1 source.

    Returns True if the aggregated file exists and is newer than the M1 file.
    Returns False if regeneration is needed.

    Parameters
    ----------
    m1_path : Path
        Path to the M1 source file.
    aggregated_dir : Path
        Directory where aggregated files live.
    target_tf : str
        Target timeframe to check.

    Returns
    -------
    bool
        True if the aggregated file is fresh (no regeneration needed).
    """
    sym = _extract_symbol_from_path(m1_path)
    category = _infer_category_from_path(m1_path)
    broker_path = _infer_broker_path_from_path(m1_path)
    pattern = f"{sym}_{target_tf}_*.csv"
    if broker_path:
        search_root = aggregated_dir / target_tf / Path(broker_path) / category / sym
    else:
        search_root = aggregated_dir / target_tf / category / sym
    agg_files = list(search_root.glob(pattern)) if search_root.exists() else []
    if not agg_files and not broker_path:
        # Fallback for ad-hoc output dirs used by tests/one-off scripts.
        agg_files = list(aggregated_dir.rglob(pattern))
    if not agg_files:
        return False

    # Check modification time
    m1_mtime = m1_path.stat().st_mtime
    newest_agg = max(f.stat().st_mtime for f in agg_files)

    return newest_agg > m1_mtime


def find_stale_aggregations(
    m1_dir: Path,
    aggregated_dir: Path,
    timeframes: Optional[Sequence[str]] = None,
) -> List[Tuple[Path, str]]:
    """Find M1 files whose aggregated outputs are stale or missing.

    Parameters
    ----------
    m1_dir : Path
        Root directory with M1 source files.
    aggregated_dir : Path
        Root directory with aggregated files.
    timeframes : sequence of str or None
        Timeframes to check.  Defaults to ``DEFAULT_TIMEFRAMES``.

    Returns
    -------
    List[Tuple[Path, str]]
        List of ``(m1_path, target_tf)`` pairs that need regeneration.
    """
    if timeframes is None:
        timeframes = DEFAULT_TIMEFRAMES

    m1_files = discover_m1_files(m1_dir)
    stale: List[Tuple[Path, str]] = []

    for m1_path in m1_files:
        for tf in timeframes:
            if not check_aggregation_freshness(m1_path, aggregated_dir, tf):
                stale.append((m1_path, tf))

    return stale


