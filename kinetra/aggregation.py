def identify_non_m1_files(data_dir: Path) -> Dict[str, List[Path]]:
    """Identify all non-M1 CSV files in master_standardized for cleanup.

    Returns a dictionary keyed by timeframe label (e.g. ``"H1"``, ``"H4"``)
    with lists of file paths that should be removed or archived once M1
    data is available and aggregation is in place.

    Parameters
    ----------
    data_dir : Path
        Root data directory (e.g. ``data/master_standardized/``).

    Returns
    -------
    Dict[str, List[Path]]
        Timeframe → list of file paths.
    """
    non_m1: Dict[str, List[Path]] = {}

    if not data_dir.exists():
        return non_m1

    for csv_path in data_dir.rglob("*.csv"):
        stem_upper = csv_path.stem.upper()
        parts = stem_upper.split("_")
        if len(parts) >= 2:
            tf_label = parts[1]
            if tf_label in ("M5", "M15", "M30", "H1", "H4", "D1", "W1"):
                non_m1.setdefault(tf_label, []).append(csv_path)

    return non_m1


def archive_non_m1_files(
    data_dir: Path,
    archive_dir: Path,
    *,
    dry_run: bool = True,
) -> Dict[str, int]:
    """Move non-M1 CSV files from master_standardized to an archive directory.

    This is a one-time migration helper.  After running, only M1 files
    remain in ``master_standardized/`` and all higher-TF files are
    safely archived (not deleted).

    Parameters
    ----------
    data_dir : Path
        Source directory (e.g. ``data/master_standardized/``).
    archive_dir : Path
        Destination archive directory.
    dry_run : bool
        If True (default), only report what would be moved.

    Returns
    -------
    Dict[str, int]
        Count of files moved (or that would be moved) per timeframe.
    """
    import shutil

    non_m1 = identify_non_m1_files(data_dir)
    counts: Dict[str, int] = {}

    for tf, paths in non_m1.items():
        counts[tf] = len(paths)
        if dry_run:
            logger.info("[DRY RUN] Would archive %d %s files", len(paths), tf)
            continue

        for src in paths:
            # Preserve the relative path structure in the archive
            rel = src.relative_to(data_dir)
            dst = archive_dir / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(src), str(dst))

        logger.info("Archived %d %s files to %s", len(paths), tf, archive_dir)

    return counts
